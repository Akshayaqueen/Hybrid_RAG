def decompose_query(query: str):
    q = query.strip()
    if any(k in q.lower() for k in ["compare", "difference", "differentiate", "vs", "versus"]):
        return [
            "Define IaaS from the document",
            "Define PaaS from the document",
            "Define SaaS from the document",
            "What are control/responsibility differences among IaaS PaaS SaaS?",
            "What are use-case and cost-model differences among IaaS PaaS SaaS?"
        ]
    parts = re.split(r"\band\b|;|,", q, flags=re.IGNORECASE)
    parts = [p.strip() for p in parts if p.strip()]
    return [q] if len(parts) <= 1 else [f"{p} (answer from the document)" for p in parts[:5]]
def merge_unique_results(list_of_result_lists, top_k=8):
    merged, seen = [], set()
    for results in list_of_result_lists:
        for r in results:
            key = (r.get("source"), r.get("page"), r.get("text", "")[:120])
            if key in seen:
                continue
            seen.add(key)
            merged.append(r)
    merged = sorted(merged, key=lambda x: x.get("rerank_score", -999), reverse=True)
    return merged[:top_k]
def build_context_from_results(results, max_chars=3500):
    parts, total = [], 0
    for r in results:
        s = f"[Source: {r['source']} | Page: {r['page']}]\n{r['text']}\n"
        if total + len(s) > max_chars:
            break
        parts.append(s)
        total += len(s)
    return "\n".join(parts)
def clean_cell_text(s: str) -> str:
    if not s:
        return "Not found in document"
    s = re.sub(r"\[Source:[^\]]+\]", " ", s)
    s = re.sub(r"\b\d+\.\s*Define\b", "Define", s, flags=re.IGNORECASE)
    s = re.sub(r"\s+", " ", s).strip()
    if len(s) > 140:
        s = s[:140].rsplit(" ", 1)[0] + "..."
    return s if len(s) >= 4 else "Not found in document"
def extract_service_model_facts(context):
    txt = re.sub(r"\s+", " ", context)
    def get_snippet(model, pattern):
        m = re.search(rf"({model}.{{0,220}}?{pattern}.{{0,140}}?[.;])", txt, flags=re.IGNORECASE)
        return clean_cell_text(m.group(1)) if m else "Not found in document"
    aspects = {
        "Definition": "is|refers to|means|definition",
        "Control": "control|managed by|responsibility|administered",
        "Cost Model": "cost|pricing|pay|subscription",
        "Use Case": "use case|used for|suitable for|best for",
        "Example": "example|e\\.g\\.|such as"
    }
    facts = {}
    for aspect, pat in aspects.items():
        facts[aspect] = {
            "IaaS": get_snippet("IaaS", pat),
            "PaaS": get_snippet("PaaS", pat),
            "SaaS": get_snippet("SaaS", pat),
        }
    return facts
def format_compare_table(facts):
    rows = ["| Aspect | IaaS | PaaS | SaaS |", "|---|---|---|---|"]
    for aspect in ["Definition", "Control", "Cost Model", "Use Case", "Example"]:
        ia = facts[aspect]["IaaS"].replace("|", "\\|")
        pa = facts[aspect]["PaaS"].replace("|", "\\|")
        sa = facts[aspect]["SaaS"].replace("|", "\\|")
        rows.append(f"| {aspect} | {ia} | {pa} | {sa} |")
    return "\n".join(rows)
def is_complex_query(query: str) -> bool:
    q = query.lower()
    triggers = [
        "compare", "difference", "vs", "versus",
        "why", "how", "analyze", "evaluate",
        "advantages and disadvantages", "pros and cons",
        "relationship between", "impact of", "trade-off", "across", "among"
    ]
    long_query = len(q.split()) >= 12
    multi_part = (" and " in q) or ("; " in q) or ("," in q and len(q.split(",")) >= 2)
    return any(t in q for t in triggers) or long_query or multi_part
def agentic_ask(query: str, use_llm=True):
    if not is_complex_query(query):
        out = ask_crag(query, use_llm=use_llm)
        out["agentic"] = {"mode": "fast_path", "complex": False, "subqueries": [query]}
        return out
    subqueries = decompose_query(query)
    sub_results, sub_debug = [], []
    for sq in subqueries:
        resp = ask_crag(sq, use_llm=False)
        sub_results.append(resp["results"])
        sub_debug.append({
            "subquery": sq,
            "status": resp["debug"]["status"],
            "confidence": resp["debug"]["confidence"],
            "top_rerank_score": resp["debug"]["top_rerank_score"]
        })
    merged = merge_unique_results(sub_results, top_k=8)
    citations = make_citations(merged) if merged else "(none)"
    if not merged:
        return {
            "answer": "I couldn't find enough evidence in the document for this complex query.",
            "citations": citations,
            "debug": {"status": "no_results", "confidence": "low"},
            "results": [],
            "agentic": {"mode": "complex_path", "complex": True, "subqueries": subqueries, "subquery_debug": sub_debug}
        }
    if not use_llm:
        return {
            "answer": "Agentic retrieval completed. (LLM synthesis disabled)",
            "citations": citations,
            "debug": {"status": "ok", "confidence": "medium"},
            "results": merged,
            "agentic": {"mode": "complex_path", "complex": True, "subqueries": subqueries, "subquery_debug": sub_debug}
        }
    context = build_context_from_results(merged)
    # deterministic compare output for stability
    if is_compare_query(query):
        facts = extract_service_model_facts(context)
        answer = format_compare_table(facts)
    else:
        prompt = f"""You are answering strictly from context.
Rules:
- Use only context.
- Provide concise structured answer.
- If evidence is insufficient, say so.
Question: {query}
Context:
{context}
Answer:"""
