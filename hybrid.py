def extract_pages_from_pdfs(pdf_files):
    """
    Input: list of PDF file paths
    Output: list of dicts -> {page, text, source}
    """
    pages = []
    for pdf_path in pdf_files:
        doc = fitz.open(pdf_path)
        for page_num, page in enumerate(doc):
            pages.append({
                "page": page_num + 1,
                "text": page.get_text(),
                "source": pdf_path
            })
    return pages

def is_noisy(text):
    """
    Heuristic cleaner to remove tiny / symbol-heavy / table-like chunks.
    """
    t = text.strip()
    if len(t) < 80:
        return True
    letters = sum(c.isalpha() for c in t)
    non_letters = len(t) - letters
    if letters == 0 or non_letters / max(letters, 1) > 1.2:
        return True
    if re.search(r'\bCO\d\b', t) and len(t.split()) < 120:
        return True
    if "CO-PO" in t:
        return True
    return False

def chunk_pages(pages, chunk_size=800, chunk_overlap=120):
    """
    Split page text into overlapping chunks for retrieval granularity.
    """
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap
    )
    documents = []
    chunk_id = 0
    for p in pages:
        chunks = splitter.split_text(p["text"])
        for ch in chunks:
            documents.append({
                "chunk_id": chunk_id,
                "text": ch,
                "page": p["page"],
                "source": p["source"]
            })
            chunk_id += 1
    # clean noisy chunks
    documents = [d for d in documents if not is_noisy(d["text"])]
    return documents

