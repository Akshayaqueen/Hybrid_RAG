def _get_query_emb(query: str):
    if query not in query_emb_cache:
        query_emb_cache[query] = embed_model.encode(
            [query],
            normalize_embeddings=True,
            convert_to_numpy=True
        ).astype("float32")
    return query_emb_cache[query]

def hybrid_retrieve_fast(
    query: str,
    top_k_faiss: int = 30,
    top_k_bm25: int = 30,
    rerank_k: int = 30,
    top_k_final: int = 5,
    w_dense: float = 0.6,
    w_bm25: float = 0.4,
    min_rerank_score: float = -10.5
):
    """
    Steps:
    1) dense retrieve (FAISS)
    2) sparse retrieve (BM25)
    3) merge + score fusion
    4) rerank with CrossEncoder
    5) dedup and return top results
    """
    q_emb = _get_query_emb(query)
    faiss_scores, faiss_ids = index.search(q_emb, top_k_faiss)
    faiss_scores, faiss_ids = faiss_scores[0], faiss_ids[0]
    q_tokens = _tokenize(query)
    bm25_scores_all = bm25.get_scores(q_tokens)
    bm25_top_ids = np.argsort(bm25_scores_all)[::-1][:top_k_bm25]
    merged = {}
    for d, s in zip(faiss_ids, faiss_scores):
        d = int(d)
        if d == -1:
            continue
        merged.setdefault(d, {"doc_id": d, "dense_score": None, "bm25_score": None})
        merged[d]["dense_score"] = float(s)
    for d in bm25_top_ids:
        d = int(d)
        merged.setdefault(d, {"doc_id": d, "dense_score": None, "bm25_score": None})
        merged[d]["bm25_score"] = float(bm25_scores_all[d])
    candidates = list(merged.values())
    if not candidates:
        return {"status": "no_results", "results": []}
    dense_vals = np.array([c["dense_score"] if c["dense_score"] is not None else 0.0 for c in candidates], dtype=np.float32)
    bm25_vals  = np.array([c["bm25_score"]  if c["bm25_score"]  is not None else 0.0 for c in candidates], dtype=np.float32)
    dense_norm = _minmax_norm(dense_vals)
    bm25_norm  = _minmax_norm(bm25_vals)
    for i, c in enumerate(candidates):
        c["fused_score"] = float(w_dense * dense_norm[i] + w_bm25 * bm25_norm[i])
    candidates = sorted(candidates, key=lambda x: x["fused_score"], reverse=True)[:rerank_k]
    pairs = [[query, documents[c["doc_id"]]["text"]] for c in candidates]
    rerank_scores = reranker.predict(pairs)
    for c, rs in zip(candidates, rerank_scores):
        c["rerank_score"] = float(rs)
        c["text"] = documents[c["doc_id"]]["text"]
        c["page"] = documents[c["doc_id"]]["page"]
        c["source"] = documents[c["doc_id"]]["source"]
    candidates = sorted(candidates, key=lambda x: x["rerank_score"], reverse=True)
    final_results = dedup_by_source_page(candidates, k=top_k_final)
    if not final_results:
        return {"status": "no_results", "results": []}
    if final_results[0]["rerank_score"] < min_rerank_score:
        return {"status": "low_confidence", "results": final_results}
    return {"status": "ok", "results": final_results}

