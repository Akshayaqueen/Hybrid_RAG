def _confidence_checks(results, min_top_score=-1.5, min_margin=0.8):
    if not results:
        return False, "no_results"
    top1 = results[0]["rerank_score"]
    top2 = results[1]["rerank_score"] if len(results) > 1 else -999.0
    margin = top1 - top2
    if top1 < min_top_score:
        return False, f"low_top_score ({top1:.3f})"
    if margin < min_margin:
        return False, f"low_margin ({margin:.3f})"
    return True, "confident"
def _simple_reformulations(query):
    variants = [
        query.strip(),
        f"Explain in simple terms: {query.strip()}",
        f"From the document, answer precisely: {query.strip()}",
        f"Key points about: {query.strip()}"
    ]
    out, seen = [], set()
    for v in variants:
        key = v.lower()
        if key not in seen:
            out.append(v)
            seen.add(key)
    return out
def hybrid_retrieve_crag(
    query: str,
    top_k_faiss: int = 30,
    top_k_bm25: int = 30,
    rerank_k: int = 30,
    top_k_final: int = 5,
    w_dense: float = 0.6,
    w_bm25: float = 0.4,
    min_rerank_score: float = -10.5,
    min_top_score: float = -1.5,
    min_margin: float = 0.8
):
    tried = []
    best_out = None
    best_top = -1e9
    for qv in _simple_reformulations(query):
        out = hybrid_retrieve_fast(
            qv,
            top_k_faiss=top_k_faiss,
            top_k_bm25=top_k_bm25,
            rerank_k=rerank_k,
            top_k_final=top_k_final,
            w_dense=w_dense,
            w_bm25=w_bm25,
            min_rerank_score=min_rerank_score
        )
        tried.append({"query_variant": qv, "status": out["status"]})
        if out["results"]:
            top = out["results"][0]["rerank_score"]
            if top > best_top:
                best_top = top
                best_out = out
        if out["status"] == "ok":
            ok, reason = _confidence_checks(out["results"], min_top_score=min_top_score, min_margin=min_margin)
            if ok:
                out["crag"] = {"used_query": qv, "confidence": "high", "reason": reason, "tried": tried}
                return out
    if best_out is None:
        return {
            "status": "no_results",
            "results": [],
            "crag": {"used_query": query, "confidence": "low", "reason": "no_results_all_variants", "tried": tried}
        }
    ok, reason = _confidence_checks(best_out["results"], min_top_score=min_top_score, min_margin=min_margin)
    if ok:
        best_out["crag"] = {"used_query": query, "confidence": "medium", "reason": reason, "tried": tried}
        return best_out
    best_out["status"] = "low_confidence"
    best_out["crag"] = {"used_query": query, "confidence": "low", "reason": reason, "tried": tried}
    return best_out

