def _tokens(text):
    return [t for t in re.findall(r"\b\w+\b", text.lower()) if t not in STOPWORDS and len(t) > 2]
def retrieval_overlap_score(query, results):
    qtok = set(_tokens(query))
    if not qtok or not results:
        return 0.0
    ctx = " ".join(r["text"] for r in results)
    ctok = set(_tokens(ctx))
    return round(len(qtok.intersection(ctok)) / max(len(qtok), 1), 4)
def groundedness_proxy(answer, results):
    if not answer or not results:
        return 0.0
    atok = set(_tokens(answer))
    if not atok:
        return 0.0
    ctx = " ".join(r["text"] for r in results)
    ctok = set(_tokens(ctx))
    return round(len(atok.intersection(ctok)) / max(len(atok), 1), 4)
def score_confidence(debug):
    c = str(debug.get("confidence", "")).lower()
    if c == "high":
        return 1.0
    if c == "medium":
        return 0.6
    if c == "low":
        return 0.2
    return 0.0
def citation_count(cits):
    if not cits or cits == "(none)":
        return 0
    return len([ln for ln in cits.split("\n") if ln.strip().startswith("- ")])
def evaluate_one(query):
    t0 = time.time()
    resp = ask(query)  # evaluates routed behavior
    e2e_ms = int((time.time() - t0) * 1000)
    dbg = resp.get("debug", {})
    results = resp.get("results", [])
    answer = resp.get("answer", "")
    cits = resp.get("citations", "")
    row = {
        "query": query,
        "route": resp.get("route"),
        "status": dbg.get("status"),
        "confidence": dbg.get("confidence"),
        "pipeline_latency_ms": dbg.get("latency_ms"),
        "end_to_end_latency_ms": e2e_ms,
        "num_results": len(results),
        "num_citations": citation_count(cits),
        "retrieval_overlap": retrieval_overlap_score(query, results),
        "groundedness_proxy": groundedness_proxy(answer, results),
        "confidence_score": score_confidence(dbg),
        "answer_chars": len(answer)
    }
    risks = []
    if row["status"] != "ok":
        risks.append("retrieval_not_ok")
    if row["confidence_score"] < 0.6:
        risks.append("low_confidence")
    if row["num_citations"] == 0:
        risks.append("no_citations")
    if row["groundedness_proxy"] < 0.25:
        risks.append("possible_hallucination_risk")
    if row["retrieval_overlap"] < 0.2:
        risks.append("weak_retrieval_match")
    row["risk_flags"] = ",".join(risks) if risks else "none"
    eval_logs.append(row)
    return resp, row
def run_eval_batch(queries):
    return [evaluate_one(q) for q in queries]
def show_eval_logs(last_n=50):
    if not eval_logs:
        print("No eval logs yet.")
        return
    display(pd.DataFrame(eval_logs).tail(last_n))
def eval_summary():
    if not eval_logs:
        print("No eval logs yet.")
        return
    df = pd.DataFrame(eval_logs)
    print("=== Eval Summary ===")
    print("Total Queries:", len(df))
    print("OK Rate:", round((df["status"] == "ok").mean() * 100, 2), "%")
    print("High Confidence Rate:", round((df["confidence"] == "high").mean() * 100, 2), "%")
    print("Avg End-to-End Latency (ms):", int(df["end_to_end_latency_ms"].mean()))
    print("Avg Retrieval Overlap:", round(df["retrieval_overlap"].mean(), 4))
    print("Avg Groundedness Proxy:", round(df["groundedness_proxy"].mean(), 4))
    print("Risk Distribution:")
    print(df["risk_flags"].value_counts())
def show_master_logs(last_n=30):
    if not master_logs:
        print("No master logs yet.")
        return
    display(pd.DataFrame(master_logs).tail(last_n))

