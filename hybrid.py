def build_context(results, max_chars=3000):
    parts, total = [], 0
    for r in results:
        s = f"[Source: {r['source']} | Page: {r['page']}]\n{r['text']}\n"
        if total + len(s) > max_chars:
            break
        parts.append(s)
        total += len(s)
    return "\n".join(parts)
def make_citations(results):
    cits = [f"- {r['source']} (Page {r['page']})" for r in results]
    out, seen = [], set()
    for c in cits:
        if c not in seen:
            out.append(c)
            seen.add(c)
    return "\n".join(out)
def extract_numbered_challenges(text):
    pattern = r'Challenge\s*(\d+)\s*[—\-:]\s*([^•\n\r]+)'
    matches = re.findall(pattern, text, flags=re.IGNORECASE)
    parsed, seen = [], set()
    for num, desc in matches:
        n = int(num)
        d = re.sub(r"\s+", " ", desc).strip(" .;:,")
        d = re.sub(r"\s+\d+\s*$", "", d).strip()
        key = (n, d.lower())
        if d and key not in seen:
            parsed.append((n, f"Challenge {n} — {d}"))
            seen.add(key)
    parsed.sort(key=lambda x: x[0])
    final, used = [], set()
    for n, line in parsed:
        if n not in used:
            final.append(line)
            used.add(n)
    return final
def is_compare_query(query: str) -> bool:
    q = query.lower()
    keys = ["difference", "differentiate", "compare", "comparison", "vs", "versus"]
    return any(k in q for k in keys)
def get_dynamic_crag_thresholds(query: str):
    min_top_score, min_margin = -1.5, 0.8
    if is_compare_query(query):
        min_margin = 0.35
    return min_top_score, min_margin

