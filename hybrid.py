def ask_crag(query: str, use_llm: bool = True, min_top_score: float = -1.5, min_margin: float = 0.8):
    t0 = time.time()
    dyn_top, dyn_margin = get_dynamic_crag_thresholds(query)
    out = hybrid_retrieve_crag(
        query=query,
        min_top_score=dyn_top if min_top_score == -1.5 else min_top_score,
        min_margin=dyn_margin if min_margin == 0.8 else min_margin,
        top_k_final=7 if is_compare_query(query) else 5
    )
    latency_ms = int((time.time() - t0) * 1000)
    top_score = out["results"][0]["rerank_score"] if out["results"] else None
    confidence = out.get("crag", {}).get("confidence", "unknown")
    reason = out.get("crag", {}).get("reason", "na")
    citations = make_citations(out["results"]) if out["results"] else "(none)"
    if out["status"] != "ok" or confidence == "low":
        answer = (
            "I’m not fully confident from the document.\n"
            "Please clarify by specifying:\n"
            "1) exact topic/keyword\n"
            "2) expected section (e.g., architecture/security/service models)\n"
            "3) answer format (definition/list/comparison)"
        )
    else:
        context = build_context(out["results"])
        ql = query.lower()
        # deterministic extraction for six challenges
        if ("challenge" in ql) and ("six" in ql or "6" in ql or "list" in ql):
            extracted = extract_numbered_challenges(context)
            if extracted:
                header = "From the document, the challenges are:"
                body = "\n".join([f"{i+1}. {line}" for i, line in enumerate(extracted)])
                if ("six" in ql or "6" in ql) and len(extracted) != 6:
                    answer = f"{header}\n{body}\n\nNote: extracted {len(extracted)} challenge items."
                else:
                    answer = f"{header}\n{body}"
            else:
                use_llm = True
        if "answer" not in locals():
            if use_llm:
                if is_compare_query(query):
                    prompt = f"""You are answering strictly from context.
Task:
- Produce a comparison table for IaaS, PaaS, SaaS.
- Rows: Definition, Control, Cost Model, Use Case, Example.
- If missing, write: Not found in document.
Question: {query}
Context:
{context}
Answer in markdown table:"""
                else:
                    prompt = f"""You are answering strictly from context.
Rules:
- Use ONLY context.
- If question asks for a list, return numbered points.
- Do not invent facts.
Question: {query}
Context:
{context}
Answer:"""
                inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=2048)
                outputs = model.generate(**inputs, max_new_tokens=260, num_beams=4, early_stopping=True)
                answer = tokenizer.decode(outputs[0], skip_special_tokens=True)
            else:
                answer = "Retrieval successful. (LLM generation disabled)"
    rag_logs.append({
        "query": query,
        "status": out["status"],
        "confidence": confidence,
        "reason": reason,
        "top_rerank_score": top_score,
        "latency_ms": latency_ms,
        "num_results": len(out["results"])
    })
    return {
        "answer": answer,
        "citations": citations,
        "debug": {
            "status": out["status"],
            "confidence": confidence,
            "reason": reason,
            "latency_ms": latency_ms,
            "top_rerank_score": top_score,
            "tried_queries": out.get("crag", {}).get("tried", []),
            "is_compare_query": is_compare_query(query)
        },
        "results": out["results"]
    }

