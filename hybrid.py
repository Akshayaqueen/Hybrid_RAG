def initialize_pipeline(pdf_files):
    """
    End-to-end initialization:
    - parse PDFs
    - chunk + clean
    - build embeddings + FAISS
    - build BM25
    - load reranker + answer model
    """
    global documents, embed_model, embeddings, index, bm25, reranker, tokenizer, model
    pages = extract_pages_from_pdfs(pdf_files)
    documents = chunk_pages(pages)
    print(f"Pages: {len(pages)}")
    print(f"Clean chunks: {len(documents)}")
    # Embedding model
    embed_model = SentenceTransformer("BAAI/bge-small-en-v1.5")
    chunk_texts = [d["text"] for d in documents]
    embeddings = embed_model.encode(
        chunk_texts,
        normalize_embeddings=True,
        show_progress_bar=True,
        convert_to_numpy=True
    ).astype("float32")
    # FAISS (dense index)
    dim = embeddings.shape[1]
    index = faiss.IndexFlatIP(dim)
    index.add(embeddings)
    # BM25 (sparse index)
    tokenized_docs = [_tokenize(d["text"]) for d in documents]
    bm25 = BM25Okapi(tokenized_docs)
    # Reranker
    reranker = CrossEncoder("cross-encoder/ms-marco-MiniLM-L-6-v2")
    # Local generator
    tokenizer = AutoTokenizer.from_pretrained("google/flan-t5-base")
    model = AutoModelForSeq2SeqLM.from_pretrained("google/flan-t5-base")
    print("✅ Pipeline initialized.")

