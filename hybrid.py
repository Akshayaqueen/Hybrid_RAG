def ask(query: str, use_llm: bool = True):
    t0 = time.time()
    if is_complex_query(query):
        resp = agentic_ask(query, use_llm=use_llm)
        route = "agentic_step4"
    else:
        resp = ask_crag(query, use_llm=use_llm)
        route = "crag_step3"
    total_ms = int((time.time() - t0) * 1000)
    dbg = resp.get("debug", {})
    master_logs.append({
        "query": query,
        "route": route,
        "status": dbg.get("status", "na"),
        "confidence": dbg.get("confidence", "na"),
        "latency_ms_total": total_ms,
        "num_results": len(resp.get("results", [])),
        "num_citations": len([x for x in resp.get("citations", "").split("\n") if x.strip().startswith("- ")])
    })
    resp["route"] = route
    resp["latency_ms_total"] = total_ms
    return resp

