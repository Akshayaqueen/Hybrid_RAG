def _tokenize(text: str):
    return re.findall(r"\b\w+\b", text.lower())
def _minmax_norm(arr):
    arr = np.asarray(arr, dtype=np.float32)
    mn, mx = arr.min(), arr.max()
    if mx - mn < 1e-8:
        return np.zeros_like(arr)
    return (arr - mn) / (mx - mn)
def dedup_by_source_page(results, k=5):
    """
    Keep one best chunk per (source,page) to avoid repetitive answers.
    """
    seen = set()
    final = []
    for r in results:
        key = (r["source"], r["page"])
        if key in seen:
            continue
        seen.add(key)
        final.append(r)
        if len(final) == k:
            break
    return final

